// Build script (esbuild) → self-contained dist/ bundles.
//
// Produces:
//   dist/plugin.mjs        — plugin bundle: plugin/index.ts + hint.mjs + core/* + minisearch.
//                            Self-contained (no ../core at runtime), default-exports {id:"skill-mcp-hint", setup}.
//   dist/plugin/index.mjs  — thin re-export of the bundle so the opencode `plugins` DIRECTORY
//                            route (which resolves <dir>/index.*, NOT package.json main) loads it.
//   dist/server.mjs        — MCP server bundle: server/index.mjs + core/* + minisearch.
//   dist/cli.mjs           — CLI bundle: cli/main.mjs + jsonc-parser (+ server imported at RUNTIME for `serve`).
//   dist/lexicon.ru-en.json— copied so the bundles' runtime `new URL("./lexicon…", import.meta.url)` resolves.
//
// No network, no writes outside dist/. Node >= 20.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";
import fs from "node:fs";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const DIST = path.join(ROOT, "dist");
const NODE_TARGET = "node20";

fs.mkdirSync(DIST, { recursive: true });

const nodeCommon = {
  bundle: true,
  format: "esm",
  platform: "node",
  target: NODE_TARGET,
  logLevel: "warning",
};

// 1) Plugin bundle (self-contained; lexicon is copied next to it).
await build({
  ...nodeCommon,
  entryPoints: [path.join(ROOT, "plugin", "index.ts")],
  outfile: path.join(DIST, "plugin.mjs"),
});

// The opencode `plugins` route needs a DIRECTORY containing index.*.
// This re-export points at the real bundle one level up (../plugin.mjs).
fs.mkdirSync(path.join(DIST, "plugin"), { recursive: true });
fs.writeFileSync(
  path.join(DIST, "plugin", "index.mjs"),
  "// Auto-generated by scripts/build.mjs — re-export of the self-contained plugin bundle.\n" +
    "// opencode resolves a `plugins` DIRECTORY entry via <dir>/index.* (not package.json main).\n" +
    'export { default } from "../plugin.mjs";\n',
  "utf8",
);

// 2) MCP server bundle (source already carries a shebang; no banner needed).
await build({
  ...nodeCommon,
  entryPoints: [path.join(ROOT, "server", "index.mjs")],
  outfile: path.join(DIST, "server.mjs"),
});

// 3) CLI bundle. jsonc-parser is bundled via its ESM build (lib/esm/main.js) —
//    the package `main` points at a UMD build whose internal require() calls
//    cannot be bundled into ESM, so we alias to the ESM entry. The `serve`
//    command imports dist/server.mjs at RUNTIME via a computed path, so
//    esbuild leaves it unbundled. cli/main.mjs already starts with a shebang —
//    esbuild preserves it as line 1.
const JSONC_ESM = path.join(ROOT, "node_modules", "jsonc-parser", "lib", "esm", "main.js");
await build({
  ...nodeCommon,
  entryPoints: [path.join(ROOT, "cli", "main.mjs")],
  outfile: path.join(DIST, "cli.mjs"),
  alias: { "jsonc-parser": JSONC_ESM },
});

// 4) Copy the lexicon next to the bundles (read at runtime via import.meta.url).
fs.copyFileSync(
  path.join(ROOT, "core", "lexicon.ru-en.json"),
  path.join(DIST, "lexicon.ru-en.json"),
);

// Make the CLI executable (no-op on Windows, meaningful on POSIX).
try {
  fs.chmodSync(path.join(DIST, "cli.mjs"), 0o755);
} catch {
  /* best-effort */
}

console.log("build ok → dist/{plugin.mjs, plugin/index.mjs, server.mjs, cli.mjs, lexicon.ru-en.json}");
